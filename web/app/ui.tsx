// Same song always gets the same placeholder colour.
function hue(id: string) {
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) % 360;
  return h;
}

export function Cover({ id, name, imageUrl, size = 44 }: { id: string; name: string; imageUrl: string | null; size?: number }) {
  if (imageUrl) {
    // eslint-disable-next-line @next/next/no-img-element
    return <img className="cover" src={imageUrl} alt="" width={size} height={size} loading="lazy" />;
  }
  const h = hue(id);
  return (
    <span
      className="cover cover-placeholder"
      style={{ width: size, height: size, background: `linear-gradient(135deg, hsl(${h} 55% 45%), hsl(${(h + 40) % 360} 60% 30%))` }}
      aria-hidden="true"
    >
      {name.trim().charAt(0).toUpperCase() || '♪'}
    </span>
  );
}

export const trackUrl = (id: string) => `https://open.spotify.com/track/${id}`;

export function timeAgo(iso: string | null) {
  if (!iso) return 'Never';
  const seconds = (Date.parse(iso) - Date.now()) / 1000;
  const units: [Intl.RelativeTimeFormatUnit, number][] = [
    ['year', 31536000],
    ['month', 2592000],
    ['week', 604800],
    ['day', 86400],
    ['hour', 3600],
    ['minute', 60],
  ];
  const rtf = new Intl.RelativeTimeFormat('en', { numeric: 'auto' });
  for (const [unit, size] of units) {
    if (Math.abs(seconds) >= size) return rtf.format(Math.round(seconds / size), unit);
  }
  return 'Just now';
}
